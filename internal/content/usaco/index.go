// entry is one problem in the cached index: the catalog view plus what
// Fetch needs to find its files.
type entry struct {
	catalog.Problem
	CPID   int    `json:"cpid"`
	Stem   string `json:"stem"`    // data/{Stem}.zip, data/sol_{Stem}.html
	HasZip bool   `json:"has_zip"` // assumed until a fetch finds a 404
	// Verified is true once the facts come from the statement itself (the
	// embedded table or a fetch). An unverified file-I/O-era problem is
	// not judgeable: its I/O file name is only in the statement.
	Verified bool `json:"verified"`
}

type index struct {
	Key     string  `json:"key"`
	Entries []entry `json:"entries"`
}

// schema changes whenever entry or the derivation rules change, so a
// stale cached index is rebuilt rather than misread.
const schema = 1

// facts.json is the statement facts for every problem in the pinned guide,
// generated by TestRegenFacts from the live statement pages. Problems the
// guide adds later fall back to div_to_probs and are verified on Fetch.
//
//go:embed facts.json
var factsJSON []byte

type factsRow struct {
	facts
	HasZip bool `json:"has_zip"`
}

func loadFactsTable() (map[int]factsRow, error) {
	var raw map[string]factsRow
	if err := json.Unmarshal(factsJSON, &raw); err != nil {
		return nil, fmt.Errorf("facts.json: %w", err)
	}
	out := make(map[int]factsRow, len(raw))
	for k, v := range raw {
		id, err := strconv.Atoi(k)
		if err != nil {
			return nil, fmt.Errorf("facts.json: key %q", k)
		}
		out[id] = v
	}
	return out, nil
}

func indexKey() string {
	sum := sha256.Sum256(factsJSON)
	return fmt.Sprintf("guide=%s schema=%d facts=%s", guide.Commit, schema, hex.EncodeToString(sum[:6]))
}

// ---- guide inputs ------------------------------------------------------------

type divProb struct {
	cpid     int
	contest  string
	title    string
	division string // lower case
	position int    // by cpid order within (division, contest)
}

// readDivToProbs reads {"Bronze": [["567", "2015 December", "Fence
// Painting"], ...], ...}. The file lists 2015-16 and later only.
func readDivToProbs(dir string) (map[int]divProb, error) {
	var raw map[string][][]string
	if err := readJSON(filepath.Join(dir, guide.DivisionList, "div_to_probs.json"), &raw); err != nil {
		return nil, err
	}
	out := map[int]divProb{}
	for div, rows := range raw {
		groups := map[string][]int{}
		for _, r := range rows {
			if len(r) < 3 {
				continue
			}
			id, err := strconv.Atoi(r[0])
			if err != nil {
				continue
			}
			out[id] = divProb{cpid: id, contest: r[1], title: r[2], division: strings.ToLower(div)}
			groups[r[1]] = append(groups[r[1]], id)
		}
		// USACO numbers a contest's problems P1..P3 in cpid order; the
		// statement header confirms it for every problem in facts.json.
		for _, ids := range groups {
			slices.Sort(ids)
			for i, id := range ids {
				p := out[id]
				p.position = i + 1
				out[id] = p
			}
		}
	}
	return out, nil
}

// readIDToSol reads {"84": "sol_ctiming.html", ...}: every USACO problem
// the guide knows, mapped to its analysis page. The stem between "sol_"
// and ".html" also names the test zip.
func readIDToSol(dir string) (map[int]string, error) {
	var raw map[string]string
	if err := readJSON(filepath.Join(dir, guide.DivisionList, "id_to_sol.json"), &raw); err != nil {
		return nil, err
	}
	out := map[int]string{}
	for k, v := range raw {
		id, err := strconv.Atoi(k)
		if err != nil {
			continue
		}
		stem := strings.TrimSuffix(strings.TrimPrefix(path.Base(v), "sol_"), ".html")
		if stem != "" && !strings.ContainsAny(stem, `/\`) {
			out[id] = stem
		}
	}
	return out, nil
}

// readSolveRates reads {"Gold": {"2016 January": [0.99, 0.94, 0.97]}}: the
// share of test cases promoters (Bronze to Gold) or the top 10 pre-college
// (Platinum) passed on P1..P3. Missing contests are null.
func readSolveRates(dir string) (map[string]map[string][]float64, error) {
	var raw map[string]map[string][]float64
	p := filepath.Join(dir, guide.DivisionList, "contest_to_points.json")
	if err := readJSON(p, &raw); err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, err
	}
	out := map[string]map[string][]float64{}
	for div, m := range raw {
		out[strings.ToLower(div)] = m
	}
	return out, nil
}

// guideProblem is what the guide's module problem lists say about one
// USACO problem, merged across every module that lists it.
type guideProblem struct {
	name    string
	source  string // "Bronze", "Old Gold", ...
	tags    []string
	modules []string
	labels  []guideLabel
}

type guideLabel struct {
	section string // "bronze", "silver", "gold", "plat", "adv", "general"
	label   string // "Easy", "Hard", ...
}

type guideRow struct {
	UniqueID   string   `json:"uniqueId"`
	Name       string   `json:"name"`
	Source     string   `json:"source"`
	Difficulty string   `json:"difficulty"`
	Tags       []string `json:"tags"`
}

// readGuideProblems walks content/**/*.problems.json and
// content/extraProblems.json. Each file is {"MODULE_ID": "...", "<list>":
// [rows...], ...}; only rows with uniqueId "usaco-<cpid>" matter here.
func readGuideProblems(dir string) (map[int]*guideProblem, error) {
	out := map[int]*guideProblem{}
	content := filepath.Join(dir, "content")
	err := filepath.WalkDir(content, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		name := d.Name()
		extra := name == "extraProblems.json"
		if d.IsDir() || (!strings.HasSuffix(name, ".problems.json") && !extra) {
			return nil
		}
		var file map[string]json.RawMessage
		if err := readJSON(p, &file); err != nil {
			return err
		}
		var module string
		if raw, ok := file["MODULE_ID"]; ok && !extra {
			_ = json.Unmarshal(raw, &module)
		}
		section := sectionOf(content, p)
		keys := make([]string, 0, len(file))
		for k := range file {
			keys = append(keys, k)
		}
		sort.Strings(keys) // stable tag order across runs
		for _, k := range keys {
			var rows []guideRow
			if json.Unmarshal(file[k], &rows) != nil {
				continue // MODULE_ID or another non-list value
			}
			for _, r := range rows {
				id, ok := usacoID(r.UniqueID)
				if !ok {
					continue
				}
				g := out[id]
				if g == nil {
					g = &guideProblem{}
					out[id] = g
				}
				g.merge(r, module, section)
			}
		}
		return nil
	})
	return out, err
}

func (g *guideProblem) merge(r guideRow, module, section string) {
	if g.name == "" {
		g.name = r.Name
	}
	if g.source == "" {
		g.source = r.Source
	}
	for _, t := range r.Tags {
		if t != "" && !slices.Contains(g.tags, t) {
			g.tags = append(g.tags, t)
		}
	}
	if module != "" && !slices.Contains(g.modules, module) {
		g.modules = append(g.modules, module)
	}
	if r.Difficulty != "" && r.Difficulty != "N/A" {
		g.labels = append(g.labels, guideLabel{section: section, label: r.Difficulty})
	}
}

func usacoID(uid string) (int, bool) {
	s, ok := strings.CutPrefix(uid, "usaco-")
	if !ok {
		return 0, false
	}
	id, err := strconv.Atoi(s)
	return id, err == nil
}

// sectionOf maps content/4_Gold/DSU.problems.json to "gold". The guide
// calls its sections general, bronze, silver, gold, plat and adv.
func sectionOf(content, p string) string {
	rel, err := filepath.Rel(content, p)
	if err != nil {
		return ""
	}
	top := strings.SplitN(filepath.ToSlash(rel), "/", 2)[0]
	_, name, ok := strings.Cut(top, "_")
	if !ok {
		return ""
	}
	switch name = strings.ToLower(name); name {
	case "advanced":
		return "adv"
	case "platinum":
		return "plat"
	}
	return name
}

func readJSON(p string, v any) error {
	b, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	if err := json.Unmarshal(b, v); err != nil {
		return fmt.Errorf("%s: %w", p, err)
	}
	return nil
}

// ---- building ----------------------------------------------------------------

// buildIndex merges the guide's tables with the embedded statement facts.
// The universe is every cpid the guide links to an analysis page
// (id_to_sol.json, 719 problems at the pinned commit) plus any listed only
// in div_to_probs or a module.
func buildIndex(guideDir string, table map[int]factsRow) (*index, error) {
	stems, err := readIDToSol(guideDir)
	if err != nil {
		return nil, err
	}
	divs, err := readDivToProbs(guideDir)
	if err != nil {
		return nil, err
	}
	rates, err := readSolveRates(guideDir)
	if err != nil {
		return nil, err
	}
	gps, err := readGuideProblems(guideDir)
	if err != nil {
		return nil, err
	}

	ids := map[int]bool{}
	for id := range stems {
		ids[id] = true
	}
	for id := range divs {
		ids[id] = true
	}
	for id := range gps {
		ids[id] = true
	}
	var sorted []int
	for id := range ids {
		sorted = append(sorted, id)
	}
	slices.Sort(sorted)

	idx := &index{Key: indexKey()}
	for _, id := range sorted {
		e := entry{CPID: id, Stem: stems[id], HasZip: true}
		row, verified := table[id]
		f := row.facts
		if verified {
			e.HasZip = row.HasZip
		} else {
			f = fallbackFacts(id, divs, gps[id])
		}
		e.Verified = verified
		if f.Division == "" || f.Title == "" {
			continue // nothing to show on a door
		}
		e.apply(f)
		g := gps[id]
		if g == nil {
			g = &guideProblem{}
		}
		e.Tags = g.tags
		e.Topic = topicFor(g.tags, g.modules)
		e.rate(g, rates)
		idx.Entries = append(idx.Entries, e)
	}
	return idx, nil
}

// fallbackFacts covers a problem missing from facts.json: div_to_probs
// knows the contest and position, a module row at least the name and
// division. Limits stay at the defaults until a fetch reads the statement.
func fallbackFacts(id int, divs map[int]divProb, g *guideProblem) facts {
	if d, ok := divs[id]; ok {
		return facts{Title: d.title, Contest: d.contest, Division: d.division, Position: d.position}
	}
	if g == nil {
		return facts{}
	}
	div := strings.ToLower(strings.TrimPrefix(g.source, "Old "))
	switch div {
	case "bronze", "silver", "gold", "platinum":
	default:
		div = ""
	}
	return facts{Title: g.name, Division: div}
}

// apply sets every statement-derived field. It is also how a fetch
// refreshes an entry, so it must not depend on guide data.
func (e *entry) apply(f facts) {
	p := &e.Problem
	p.ID = catalog.ID(fmt.Sprintf("usaco:%d", e.CPID))
	p.Source = catalog.USACO
	p.Title = f.Title
	p.URL = statementURL(e.CPID)
	p.Division = f.Division
	p.Position = f.Position
	p.Contest = contestString(f)
	p.TimeLimit = f.TimeLimit
	if p.TimeLimit == 0 {
		p.TimeLimit = defaultTime
	}
	p.MemLimit = f.MemLimit
	if p.MemLimit == 0 {
		p.MemLimit = defaultMem
	}
	p.FileIO = f.FileIO
	p.Interactive = f.Interactive
	p.NeedsChecker = f.NeedsChecker
	p.FloatTolerance = f.FloatTolerance
	p.HasEditorial = e.Stem != ""
	e.judgeable()
}

func (e *entry) judgeable() {
	// Before Dec 2020 every problem used file I/O; without the statement
	// the file name is unknown, so an unverified old problem is not
	// offered.
	ioKnown := e.Verified || e.CPID >= firstStdinCPID
	e.Judgeable = e.HasZip && e.Stem != "" && ioKnown && !e.Interactive && !e.NeedsChecker
}

// firstStdinCPID is 2020 December Bronze P1, the first contest that read
// stdin and wrote stdout.
const firstStdinCPID = 1059

func contestString(f facts) string {
	switch {
	case f.Contest == "":
		return ""
	case f.Position == 0:
		return fmt.Sprintf("%s, %s", f.Contest, titleCase(f.Division))
	}
	return fmt.Sprintf("%s, %s P%d", f.Contest, titleCase(f.Division), f.Position)
}

func statementURL(cpid int) string {
	return fmt.Sprintf("https://usaco.org/index.php?page=viewproblem2&cpid=%d", cpid)
}

// rate fills Rating and RatingSource: the division/position table, then
// the guide's labels from home-section modules, then the contest's solve
// rates.
func (e *entry) rate(g *guideProblem, rates map[string]map[string][]float64) {
	era := eraDivision(e.CPID, e.Division)
	var labels []string
	for _, l := range g.labels {
		if isHomeSection(era, l.section) {
			labels = append(labels, l.label)
		}
	}
	r, src := estimate(era, e.Position, labels)
	contest := strings.SplitN(e.Contest, ",", 2)[0]
	if d, ok := solveRateDelta(rates[e.Division][contest], e.Position); ok {
		r += d
		src += "+solve-rate"
	}
	e.Rating, e.RatingSource = r, src
}

// solveRateDelta compares a problem's solve rate with its two siblings in
// the same contest and division. The populations (promoters, or the top 10
// in Platinum) differ between divisions, but within one contest and
// division the three numbers come from the same contestants, so a P2 that
// promoters scored 47% on while P1 and P3 got 99% and 92% (2016 US Open
// Bronze) is harder than its position says. Delta is 300 rating points per
// unit of rate below the siblings' mean, clamped to ±150: near-equal rates
// (0.99 vs 0.97, the common case) move the rating by a few points.
func solveRateDelta(row []float64, position int) (int, bool) {
	if len(row) != 3 || position < 1 || position > 3 {
		return 0, false
	}
	self := row[position-1]
	var sib float64
	for i, v := range row {
		if i != position-1 {
			sib += v / 2
		}
	}
	d := int(math.Round(300 * (sib - self)))
	return min(max(d, -150), 150), true
}

// ---- persistence -------------------------------------------------------------

func loadIndex(p string) (*index, bool) {
	b, err := os.ReadFile(p)
	if err != nil {
		return nil, false
	}
	var idx index
	if json.Unmarshal(b, &idx) != nil || idx.Key != indexKey() || len(idx.Entries) == 0 {
		return nil, false
	}
	return &idx, true
}

func saveIndex(p string, idx *index) error {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", " ")
	if err := enc.Encode(idx); err != nil {
		return err
	}
	return writeAtomic(p, buf.Bytes())
}

// writeAtomic writes via a temp file in the same dir and a rename, so a
// reader (or a crash) never sees half a file.
func writeAtomic(p string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(filepath.Dir(p), ".tmp-"+filepath.Base(p)+"-")
	if err != nil {
		return err
	}
	defer os.Remove(f.Name()) // no-op after the rename
	if _, err := f.Write(data); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	return os.Rename(f.Name(), p)
}
