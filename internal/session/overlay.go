package session

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// ArgForce, after submit, submits although the samples fail: :Submit!.
const ArgForce = "force"

// Overlay is the vimscript the game's vim sources with -S, after the user's
// own vimrc, which loads as usual. It defines the game's commands; each runs
// `katharsis ctl` as a job (vim 8+ +job), so vim never waits on the judge,
// and shows the answer in the message line when it comes.
//
//	:Submit[!]   write the buffer if modified, judge the full tests; while
//	             the samples fail the game refuses :Submit, and :Submit!
//	             (ctl submit force) submits anyway
//	:Debug [n]   write if modified, open lldb on test n (default: the
//	             first failing test)
//	:Quack       use a rubber duck
//	:Retreat     swap the door for a life
//	:GiveUp      confirm, then give up (crash; the editorial opens)
type Overlay struct {
	// Ctl is the argv that reaches the game, normally the absolute path of
	// this binary and "ctl"; the command and its arguments follow it.
	Ctl []string
	// QuitGivesUp makes an exact `:q!` run :GiveUp, which asks first;
	// answering no leaves vim as it was. It is a command-line abbreviation
	// that fires only when the whole line is q!, so :qa!, :wq, :x, :quit!,
	// `:e! | q!` and ZQ behave as always.
	QuitGivesUp bool
}

func (o Overlay) script() string {
	var ctl []string
	for _, a := range o.Ctl {
		ctl = append(ctl, vimString(a))
	}
	s := strings.Replace(overlayScript, "{{CTL}}", "["+strings.Join(ctl, ", ")+"]", 1)
	if o.QuitGivesUp {
		s += quitGivesUp
	}
	return s
}

// Write writes the script to path, replacing it atomically: vim may be
// sourcing an older one.
func (o Overlay) Write(path string) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".overlay-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name()) // gone once renamed
	if _, err := tmp.WriteString(o.script()); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// EditorArgv is the editor command to hand SplitEditor. editor is a shell
// command line, as --editor takes it (`vim -c "set nu"`): sh runs it with
// `-S overlay` (for vim) and the file SplitEditor appends as its last
// arguments, and its exec leaves the editor the pane's own process. Split
// on spaces instead, a quoted argument broke apart and vim opened its
// pieces as files. It all runs under env(1) with $KATHARSIS_SOCK set,
// because the pane gets the tmux server's environment rather than ours.
// neovim gets no overlay (its job API differs), only the variable.
func EditorArgv(editor, sock, overlay string) []string {
	argv := []string{"env", sockEnv + "=" + sock, "sh", "-c", "exec " + editor + ` "$@"`, "katharsis"}
	if overlay != "" && isVim(EditorName(editor)) {
		argv = append(argv, "-S", overlay)
	}
	return argv
}

// EditorName is the program an editor command line runs: its first word,
// unquoted.
func EditorName(editor string) string {
	s := strings.TrimLeft(editor, " \t")
	if s == "" {
		return ""
	}
	if q := s[0]; q == '\'' || q == '"' {
		name, _, _ := strings.Cut(s[1:], string(q))
		return name
	}
	name, _, _ := strings.Cut(s, " ")
	name, _, _ = strings.Cut(name, "\t")
	return name
}

// CheckEditor reports an editor command line whose program is not there.
// Started anyway, its pane dies at once, taking sh's "not found" with it.
func CheckEditor(editor string) error {
	name := EditorName(editor)
	if name == "" {
		return errors.New("the editor command is empty")
	}
	if rest, ok := strings.CutPrefix(name, "~/"); ok {
		if home, err := os.UserHomeDir(); err == nil {
			name = filepath.Join(home, rest)
		}
	}
	if _, err := exec.LookPath(name); err != nil {
		return fmt.Errorf("editor %q: %w", editor, err)
	}
	return nil
}

func isVim(cmd string) bool {
	switch filepath.Base(cmd) {
	case "vim", "vi", "gvim", "mvim", "vimx":
		return true
	}
	return false
}

// vimString quotes s as a single-quoted vimscript string, where only the
// quote itself needs escaping (by doubling).
func vimString(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}

// overlayScript avoids lambdas: partials of script functions carry the job
// state, so there is no closure capture to get wrong. The answer shows once
// both the job has exited (its status picks the highlight) and its channel
// has closed (all output read); vim calls those two in either order.
const overlayScript = `" katharsis overlay, generated by the game; sourced with vim -S after your
" vimrc. Each command runs ` + "`katharsis ctl`" + ` as a job, so vim never waits.
if !has('job')
  echohl WarningMsg
  echomsg 'katharsis: this vim has no +job; :Submit and the rest are off'
  echohl None
  finish
endif

let s:ctl = {{CTL}}

function! s:Show(st) abort
  if !a:st.closed || a:st.status < 0
    return
  endif
  let l:text = 'katharsis: ' . join(a:st.lines, ' ')
  redraw
  if a:st.status != 0
    echohl ErrorMsg
  endif
  " :messages keeps the whole reply; the message line shows what fits.
  echomsg l:text
  let l:fit = s:Fit(l:text)
  if l:fit !=# l:text
    redraw
    echo l:fit
  endif
  echohl None
endfunction

" s:Fit keeps text to the message line by cutting its tail: vim cuts a
" longer message in the middle (shortmess T), and the middle is where a
" reply says what a submit costs. The prefix goes first.
function! s:Fit(text) abort
  let l:room = exists('v:echospace') ? v:echospace
        \ : &columns - 1 - (&ruler ? 18 : 0) - (&showcmd ? 11 : 0)
  let l:text = a:text
  if strdisplaywidth(l:text) > l:room
    let l:text = substitute(l:text, '^katharsis: ', '', '')
  endif
  if strdisplaywidth(l:text) <= l:room
    return l:text
  endif
  while strchars(l:text) > 0 && strdisplaywidth(l:text) > l:room - 1
    let l:text = strcharpart(l:text, 0, strchars(l:text) - 1)
  endwhile
  return l:text . '…'
endfunction

function! s:Out(st, ch, msg) abort
  call add(a:st.lines, a:msg)
endfunction

function! s:Exit(st, job, status) abort
  let a:st.status = a:status
  call s:Show(a:st)
endfunction

function! s:Close(st, ch) abort
  let a:st.closed = 1
  call s:Show(a:st)
endfunction

function! s:Ctl(...) abort
  let l:st = {'lines': [], 'status': -1, 'closed': 0}
  let l:job = job_start(s:ctl + a:000, {
        \ 'in_io': 'null',
        \ 'err_io': 'out',
        \ 'out_cb': function('s:Out', [l:st]),
        \ 'exit_cb': function('s:Exit', [l:st]),
        \ 'close_cb': function('s:Close', [l:st]),
        \ })
  if job_status(l:job) ==# 'fail'
    echohl ErrorMsg
    echomsg 'katharsis: cannot run ' . s:ctl[0]
    echohl None
  endif
endfunction

" save: write the current buffer first, so the judge sees what is on screen.
" A failed write aborts the command rather than judging a stale file.
function! s:Run(save, ...) abort
  if a:save && &modified && &buftype ==# ''
    update
  endif
  echo 'katharsis: ' . a:1 . '...'
  call call('s:Ctl', a:000)
endfunction

function! s:GiveUp() abort
  if confirm('Give up? The boot crashes and the editorial opens.', "&Yes\n&No", 2) == 1
    call s:Ctl('giveup')
  endif
endfunction

function! s:Submit(force) abort
  if a:force
    call s:Run(1, 'submit', 'force')
  else
    call s:Run(1, 'submit')
  endif
endfunction

command! -bar -bang Submit call s:Submit(<bang>0)
command! -bar -nargs=? Debug call s:Run(1, 'debug', <f-args>)
command! -bar Quack call s:Run(0, 'quack')
command! -bar Retreat call s:Run(0, 'retreat')
command! -bar GiveUp call s:GiveUp()
`

const quitGivesUp = `
" :q! gives up, after asking. Only the exact command line q! is rewritten.
cnoreabbrev <expr> q! getcmdtype() ==# ':' && getcmdline() ==# 'q!' ? 'GiveUp' : 'q!'
`
